// Produce a dependency-free module for Cloudflare's browser editor.
import {readFile,writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
let shared=await readFile(new URL("../free-probe/worker.mjs",import.meta.url),"utf8");
let application=await readFile(new URL("worker.mjs",import.meta.url),"utf8");
if(!shared.includes("export default {") || !shared.includes("export class ProbeLedger") ||
   !application.startsWith('import {ProbeLedger,Failure,boundedBytes,reply} from "../free-probe/worker.mjs";')) throw Error("Source layout changed; review bundling.");
shared=shared.replace("export {Failure, boundedBytes, reply};","")
  .replace("export default {","const isolatedProbeHandler = {")
  .replace("export class ProbeLedger","class ProbeLedger");
application=application.slice(application.indexOf("\n")+1);
const result="// Generated by build-dashboard.mjs. No secrets. Keep ENABLE_FREE_MESSENGER=false during setup.\n"+
  "const {ProbeLedger,Failure,boundedBytes,reply}=(()=>{\n"+shared+
  "\nreturn {ProbeLedger,Failure,boundedBytes,reply};\n})();\n"+application;
if(/^import\s/m.test(result)) throw Error("Unexpected external import.");
await writeFile(new URL("worker-dashboard.mjs",import.meta.url),result);
console.log("worker-dashboard.mjs: "+Buffer.byteLength(result)+" bytes; SHA-256 "+createHash("sha256").update(result).digest("hex"));
