// Bundle the production entry for local workerd tests and the dashboard editor.
import {build} from "esbuild";
import {fileURLToPath} from "node:url";
export async function bundleWorker(outfile) {
  await build({entryPoints:[fileURLToPath(new URL("worker.mjs",import.meta.url))],outfile,bundle:true,format:"esm",platform:"browser",target:"es2022",
    banner:{js:"// Generated by build-dashboard.mjs. No credentials included."}});
  return outfile;
}
